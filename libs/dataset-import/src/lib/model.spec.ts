import { PROJECT_ID_PATTERN, firstEntry, projectIdFromFile } from './model';

describe('projectIdFromFile', () => {
  it('takes the name of the file without its extension', () => {
    expect(projectIdFromFile('canciones.json')).toBe('canciones');
  });

  it('turns what the pattern does not take into dashes and drops the accents', () => {
    expect(projectIdFromFile('Mis canciones de verano!.html')).toBe('Mis-canciones-de-verano');
    expect(projectIdFromFile('canción número 1.json')).toBe('cancion-numero-1');
  });

  it('starts with a letter or a number and is at most 64 long', () => {
    expect(projectIdFromFile('---abc.json')).toBe('abc');
    expect(projectIdFromFile(`${'a'.repeat(80)}.json`)).toHaveLength(64);
  });

  it('answers an empty name when nothing is left', () => {
    expect(projectIdFromFile('###.json')).toBe('');
  });

  it('is always accepted by the id pattern, or empty', () => {
    for (const f of ['x.json', 'Ñandú & co.json', '2024-01-01 lista.html', '.hidden.json']) {
      const id = projectIdFromFile(f);
      expect(id === '' || PROJECT_ID_PATTERN.test(id), f).toBe(true);
    }
  });
});

describe('firstEntry', () => {
  const music = 'project: x\ntracks:\n  - id: "1"\n    prompt: Synthpop de los 80\n    lyrics: |\n      Luces de neón\n      en la ciudad\n    bpm: 118\n  - id: "2"\n    prompt: Ambient\n';

  it('takes the style and the lyrics of the first track, and leaves the title to the dashboard when the id is just a number', () => {
    expect(firstEntry(music, 'music')).toEqual({ title: '', style: 'Synthpop de los 80', tags: '', lyrics: 'Luces de neón\nen la ciudad' });
  });

  it('uses the id as the title when it is a name', () => {
    expect((firstEntry('tracks:\n  - id: neon-nights\n    prompt: Synthpop\n', 'music'))?.title).toBe('neon-nights');
  });

  it('reads the scenes of a video project', () => {
    expect(firstEntry('scenes:\n  - id: s1\n    prompt: A beach\n', 'video')).toEqual({ title: 's1', style: 'A beach', tags: '', lyrics: '' });
  });

  it('is null with no tracks or a file that is not a project', () => {
    expect(firstEntry('tracks: 4\n', 'music')).toBeNull();
    expect(firstEntry('project: [unclosed', 'music')).toBeNull();
    expect(firstEntry('', 'music')).toBeNull();
  });

  it('reads what the real server writes: the first track of its file, with its comments and settings around', () => {
    const real = '# Generated by `orchestrator import --mode music`.\n\nproject: imported\n\noutput:\n  mode: music\n\ndefaults:\n  music:\n    # models_dir: models/music\n\ntracks:\n  - id: "1"\n    prompt: Synthpop de los 80\n    lyrics: Luces de neón en la ciudad\n    duration_seconds: 90\n    bpm: 118\n    vocal_language: es\n  - id: "2"\n    prompt: Ambient\n';
    expect(firstEntry(real, 'music')).toEqual({ title: '', style: 'Synthpop de los 80', tags: '', lyrics: 'Luces de neón en la ciudad' });
  });

  it('reads quoted text with escapes, a long line folded over several, and a block of lines', () => {
    const yaml = 'tracks:\n  - id: "a-1"\n    prompt: "Say \\"hi\\", then\\nleave"\n    lyrics: |-\n      line one\n\n      line two\n  - id: b\n';
    expect(firstEntry(yaml, 'music')).toEqual({ title: 'a-1', style: 'Say "hi", then\nleave', tags: '', lyrics: 'line one\n\nline two' });
    const folded = 'tracks:\n  - id: x\n    prompt: a long description that the writer\n      folded over two lines\n    lyrics: \'it\'\'s fine\'\n';
    expect(firstEntry(folded, 'music')).toEqual({ title: 'x', style: 'a long description that the writer folded over two lines', tags: '', lyrics: "it's fine" });
  });

  it('takes nothing from the second track', () => {
    expect(firstEntry('tracks:\n  - id: a\n    prompt: one\n  - id: b\n    prompt: two\n    lyrics: la\n', 'music')).toEqual({ title: 'a', style: 'one', tags: '', lyrics: '' });
  });

  it('reads the tags the server writes from a dataset with a Tags line, spaced', () => {
    const yaml = 'tracks:\n  - id: neon\n    prompt: Synthpop de los 80, brillante\n    lyrics: Luces\n    bpm: 118\n    tags: synthpop,80s,female vocal\n';
    expect(firstEntry(yaml, 'music')).toEqual({ title: 'neon', style: 'Synthpop de los 80, brillante', tags: 'synthpop, 80s, female vocal', lyrics: 'Luces' });
  });
});
